#!/usr/bin/env python3
"""Refresh the vendored Quickwit API surface.

The MCP server in rust-backend/src/mcp.rs wraps a hand-picked, read-only subset
of Quickwit's REST API. `quickwit_api_surface_is_current` and its sibling tests
check that subset against the file this script writes, so a Quickwit upgrade that
moves, renames or removes an endpoint fails `cargo test` instead of failing
silently at runtime against a 404.

Run it after every Quickwit upgrade, then review the diff:

    python ci/refresh-quickwit-api-surface.py                      # against localhost:7280
    python ci/refresh-quickwit-api-surface.py http://quickwit:7280

Only the fields the tests need are kept -- the full OpenAPI document is ~67 KB
of schemas whose churn would bury the one line that matters in review.
"""

from __future__ import annotations

import json
import pathlib
import sys
import urllib.request

DEFAULT_URL = "http://localhost:7280"
OUT = pathlib.Path(__file__).resolve().parent.parent / "rust-backend" / "quickwit-api-surface.json"
HTTP_METHODS = ("get", "post", "put", "delete", "patch")


def main() -> int:
    base = (sys.argv[1] if len(sys.argv) > 1 else DEFAULT_URL).rstrip("/")
    url = f"{base}/openapi.json"

    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            spec = json.load(resp)
    except Exception as exc:  # noqa: BLE001 - any failure here is fatal and worth printing
        print(f"could not fetch {url}: {exc}", file=sys.stderr)
        print(
            "Point this at a running Quickwit; with the cluster in Kubernetes:\n"
            "  kubectl -n quickwit port-forward svc/quickwit-searcher 7280:7280",
            file=sys.stderr,
        )
        return 1

    operations = sorted(
        (
            {
                "method": method.upper(),
                "path": path,
                "operation_id": op.get("operationId", ""),
                "tags": op.get("tags", []),
            }
            for path, ops in spec.get("paths", {}).items()
            for method, op in ops.items()
            if method in HTTP_METHODS
        ),
        key=lambda o: (o["path"], o["method"]),
    )

    surface = {
        "_comment": "Generated by ci/refresh-quickwit-api-surface.py -- do not hand-edit.",
        "quickwit_version": spec.get("info", {}).get("version", "unknown"),
        "operations": operations,
    }

    previous = None
    if OUT.exists():
        previous = json.loads(OUT.read_text(encoding="utf-8"))

    OUT.write_text(json.dumps(surface, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[1])}: "
          f"{len(operations)} operations from Quickwit {surface['quickwit_version']}")

    if previous:
        before = {(o["method"], o["path"]) for o in previous["operations"]}
        after = {(o["method"], o["path"]) for o in operations}
        if previous.get("quickwit_version") != surface["quickwit_version"]:
            print(f"  version: {previous.get('quickwit_version')} -> {surface['quickwit_version']}")
        for m, p in sorted(after - before):
            print(f"  + {m} {p}")
        for m, p in sorted(before - after):
            print(f"  - {m} {p}   <-- REMOVED upstream; check mcp.rs still works")
        if before == after:
            print("  no endpoint changes")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
